# ensure model dir
Path("models").mkdir(exist_ok=True)

# แปลงข้อมูลจาก List เป็น pandas DataFrame
df = pd.DataFrame(TRAINING_DATA)

# ปรับชื่อคอลัมน์ให้เป็นมาตรฐาน text/label (เพื่อความครอบคลุม)
rename_map = {}
if "ข้อความ" in df.columns and "text" not in df.columns:
    rename_map["ข้อความ"] = "text"
df = df.rename(columns=rename_map)

# ตรวจคอลัมน์จำเป็น
if "label" not in df.columns:
    raise SystemExit("❌ ไม่พบคอลัมน์ 'label' ในข้อมูล")
if "text" not in df.columns:
    raise SystemExit("❌ ไม่พบคอลัมน์ 'text' ในข้อมูล")

# ทำความสะอาดขั้นต้น
df = df.dropna(subset=["text", "label"])
df["text"] = df["text"].astype(str).str.strip()
df = df[df["text"] != ""].drop_duplicates(subset=["text"]).reset_index(drop=True)

# ตรวจสอบจำนวนข้อมูลว่ามีพอสำหรับการแบ่ง Train/Test หรือไม่
if len(df) < 5:
    raise SystemExit("❌ ข้อมูลน้อยเกินไป กรุณาเพิ่มข้อมูลใน TRAINING_DATA ให้มากกว่านี้")

# แยก train/test
X_train, X_test, y_train, y_test = train_test_split(
    df["text"], df["label"],
    test_size=TEST_SIZE,
    random_state=RANDOM_STATE,
    stratify=df["label"]
)

# Pipeline: สำหรับภาษาไทยชุดเล็ก ลองใช้ char-ngrams จะจับ pattern ได้ดีขึ้น
# ปรับตัวเลขนี้ใน pipeline
pipe = Pipeline([
    ("tfidf", TfidfVectorizer(
        analyzer="char_wb",
        ngram_range=(3,5),
        min_df=2,              # ปรับจาก 1 เป็น 2 เพื่อให้ฉลาดขึ้น
        max_features=30000
    )),
    ("clf", LogisticRegression(max_iter=1000, class_weight='balanced')) # เพิ่ม class_weight='balanced'
])
print(df["label"].value_counts())
# เทรน
pipe.fit(X_train, y_train)

# ประเมิน
pred = pipe.predict(X_test)
print("\nClassification report (test set):")
print(classification_report(y_test, pred, digits=3, zero_division=0))

# cross-val (ประเมินรวมๆ เพิ่มเติม) - ปรับ cv ให้เหมาะสมกับจำนวนข้อมูล
min_class_count = df["label"].value_counts().min()
cv_folds = min(5, min_class_count)

if cv_folds >= 2:
    try:
        scores = cross_val_score(pipe, df["text"], df["label"], cv=cv_folds)
        print(f"\nCross-val accuracy ({cv_folds}-fold): {scores.mean():.3f} ± {scores.std():.3f}")
    except Exception as e:
        print(f"\nไม่สามารถทำ Cross-val ได้เนื่องจากข้อมูลแต่ละกลุ่มอาจยังมีน้อยเกินไป: {e}")
else:
    print(f"\nข้ามการทำ Cross-val เนื่องจากข้อมูลบางกลุ่มมีน้อยกว่า 2 รายการ")

# เซฟโมเดล
joblib.dump(pipe, MODEL_PATH)
print(f"\n✅ saved → {MODEL_PATH}")